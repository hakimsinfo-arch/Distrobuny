"""Assemble the EFI System Partition tree (build/esp).

Boot chain (all binaries unmodified, signatures intact):

  firmware -> \\EFI\\BOOT\\BOOTX64.EFI  shim, signed by the Microsoft UEFI CA
           -> \\EFI\\BOOT\\grubx64.efi  GRUB, signed by Canonical
           -> \\distrobuny\\vmlinuz      Linux, signed by Canonical
              + \\distrobuny\\initramfs.img (the Distro Buny runtime)

Canonical's signed GRUB has /EFI/ubuntu compiled in as its prefix, so the
configuration is installed both there and next to the binary.  The shim
fallback (fbx64.efi) is deliberately not installed: it would create
firmware boot entries on the user's computer.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from .. import util
from ..util import WORKSPACE, BuildError, info, step
from . import components, runtime

ESP = WORKSPACE / "build" / "esp"

GRUB_CFG = r"""# Distro Buny boot configuration (generated by tools/build/buny-build; edits are overwritten)
# Hold Esc while starting to show this menu.
set default=distrobuny
set timeout_style=hidden
set timeout=1
set gfxpayload=keep
set buny_extra=""
# Kernel parameters every runtime entry needs.  kho=off: kexec handover (on by
# default in this kernel) would confine the next system's kernel and initrd to
# small pre-reserved scratch areas, so large installer initrds (openSUSE DVD:
# 349 MiB) could not be loaded.  Distro Buny hands nothing over, so it is off.
set buny_base="kho=off"

# The partition GUID of this ESP lets the runtime find its own drive.
if [ -z "$buny_esp" ]; then
    probe --set buny_esp --part-uuid "$root"
fi

# Optional per-drive options, e.g. lab automation: set buny_extra="buny.lab=1 console=ttyS0,115200"
if [ -f /distrobuny/options.cfg ]; then
    source /distrobuny/options.cfg
fi

menuentry "Distro Buny" --id distrobuny {
    echo "Starting Distro Buny..."
    linux /distrobuny/vmlinuz buny.esp=$buny_esp $buny_base quiet loglevel=3 vt.global_cursor_default=0 $buny_extra
    initrd /distrobuny/initramfs.img
}

menuentry "Distro Buny (diagnostic mode)" --id diagnostic {
    linux /distrobuny/vmlinuz buny.esp=$buny_esp $buny_base buny.debug=1 loglevel=7 $buny_extra
    initrd /distrobuny/initramfs.img
}

submenu "Advanced options" {
    menuentry "Distro Buny emergency shell" {
        linux /distrobuny/vmlinuz buny.esp=$buny_esp $buny_base buny.shell=1 loglevel=7 $buny_extra
        initrd /distrobuny/initramfs.img
    }
    menuentry "Enroll a Secure Boot key (MOK manager)" {
        chainloader /EFI/BOOT/mmx64.efi
    }
    menuentry "UEFI firmware settings" {
        fwsetup
    }
    menuentry "Restart" {
        reboot
    }
    menuentry "Shut down" {
        halt
    }
}
"""


