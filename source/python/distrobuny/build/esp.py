LICENSE_TEXTS = WORKSPACE / "assets" / "licenses"


def _notice_row(name: str, license: str, sources: dict[str, str]) -> str:
    return f"  {name:<38}  {license}\n      source: {', '.join(f'{k} {v}' for k, v in sources.items())}\n"


def licenses_txt() -> str:
    rows = "".join(_notice_row(c["name"], c["license"], c["source"]) for c in components.shipped())
    libc, libc_version = components.libc_source()
    rows += "Statically linked into buny-init, buny-ui and buny-preinit:\n"
    rows += _notice_row(f"GNU C Library {components.upstream_version(libc_version)}", "LGPL-2.1-or-later",
                        {libc: libc_version})
    return LICENSES_HEAD + rows + LICENSES_TAIL


def install_licenses(dest: Path) -> None:
    """Full licence texts plus the Debian copyright files of everything shipped."""
    dest.mkdir(parents=True)
    for txt in sorted(LICENSE_TEXTS.glob("*.txt")):
        shutil.copy2(txt, dest / txt.name)
    for c in components.shipped():
        for f in sorted((components.extract(c["component"]) / "usr" / "share" / "doc").glob("*/copyright")):
            shutil.copyfile(f, dest / f"{f.parent.name}.copyright.txt")
    libc = Path("/usr/share/doc/libc6/copyright")
    if not libc.exists():
        raise BuildError(f"{libc} is missing; it carries the C library's copyright notices")
    shutil.copyfile(libc, dest / "libc6.copyright.txt")


def build_esp_tree(lab: bool = False) -> Path:
    info("assembling the EFI System Partition")
    rt = WORKSPACE / "build" / "runtime"
    if not (rt / "vmlinuz").exists() or not (rt / "initramfs.img").exists():
        runtime.build_runtime()
    shim = components.extract("shim-signed")
    grub = components.extract("grub-efi-amd64-signed")
    if ESP.exists():
        shutil.rmtree(ESP)
    boot = ESP / "EFI" / "BOOT"
    boot.mkdir(parents=True)
    (ESP / "EFI" / "ubuntu").mkdir(parents=True)
    (ESP / "distrobuny").mkdir(parents=True)
    pairs = [
        (shim / "usr/lib/shim/shimx64.efi.signed.latest", boot / "BOOTX64.EFI"),
        (shim / "usr/lib/shim/mmx64.efi", boot / "mmx64.efi"),
        (grub / "usr/lib/grub/x86_64-efi-signed/grubx64.efi.signed", boot / "grubx64.efi"),
        (rt / "vmlinuz", ESP / "distrobuny" / "vmlinuz"),
        (rt / "initramfs.img", ESP / "distrobuny" / "initramfs.img"),
    ]
    for src, dst in pairs:
        if not src.exists():
            raise BuildError(f"missing boot component {src}")
        shutil.copy2(src, dst)
    for cfg in (boot / "grub.cfg", ESP / "EFI" / "ubuntu" / "grub.cfg"):
        cfg.write_text(GRUB_CFG)
    # licence notices travel with every image
    (ESP / "distrobuny" / "LICENSES.txt").write_text(licenses_txt())
    install_licenses(ESP / "distrobuny" / "licenses")
    shutil.copy2(WORKSPACE / "assets" / "distro-icons" / "ATTRIBUTION.md", ESP / "distrobuny" / "ICON-ATTRIBUTION.md")
    if lab:
        (ESP / "distrobuny" / "options.cfg").write_text(
            'set buny_extra="buny.lab=1 console=tty0 console=ttyS0,115200"\n')
    build = {
        "version": (WORKSPACE / "VERSION").read_text().strip(),
        "runtime": json.loads((rt / "runtime.json").read_text()),
        "files": {str(p.relative_to(ESP)): util.sha256_file(p) for p in sorted(ESP.rglob("*")) if p.is_file()},
        "lab": lab,
    }
    (ESP / "distrobuny" / "build.json").write_text(json.dumps(build, indent=2) + "\n")
    total = sum(p.stat().st_size for p in ESP.rglob("*") if p.is_file())
    step(f"ESP tree ready: {util.human_size(total)} in {ESP}")
    return ESP
